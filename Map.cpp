void Map::draw(int offsetX, int offsetY) const  // Rysowanie œcian mapy
{
    for (int y = 0; y < getHeight(); y++) {
        for (int x = 0; x < getWidth(); x++) {
            int posX = offsetX + x * getcellSize();
            int posY = offsetY + y * getcellSize();

            if (grid[y][x] == 1) {
                DrawRectangle(posX, posY, getcellSize(), getcellSize(), GRAY); // Œciana
            }
        }
    }

}

bool Map::isWall(int x, int y) const    // Sprawdzanie, czy dane pole to œciana
{
    if (x < 0 || x >= width || y < 0 || y >= height) return true; // Poza granicami traktowane jako œciana
    return grid[y][x] == 1;
}



